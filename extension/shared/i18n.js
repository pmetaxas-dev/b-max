/**
 * The language of a text the user wrote, by the server's rule
 * (domain.GoalLanguage): Greek when at least a quarter of its letters are Greek.
 */
export function langOf(text) {
  const greek = (text.match(/\p{Script=Greek}/gu) ?? []).length;
  const latin = (text.match(/\p{Script=Latin}/gu) ?? []).length;
  return greek > 0 && greek * 3 >= latin ? 'el' : 'en';
}

/** The text table for lang, English for anything unknown. */
export function t(lang) {
  return TEXT[lang] ?? TEXT.en;
}
